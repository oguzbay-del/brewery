#!/usr/bin/env python3
"""Generate the iOS color assets and Tokens.swift from tasarim-sistemi/tokens.json.

Usage:
    python3 -I ios/scripts/gen_colors.py           # write files
    python3 -I ios/scripts/gen_colors.py --check   # exit 1 if generated files are stale

Theme mapping:
    light    -> universal appearance (no appearances entry)
    dark     -> appearances: luminosity=dark
    contrast -> appearances: contrast=high (light + high contrast).
                Dark + high contrast uses the contrast-dark value, falling
                back to the dark value if a token defines none.
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "tasarim-sistemi" / "tokens.json"
RES = ROOT / "ios" / "Demleme" / "Resources" / "Assets.xcassets"
COLORS = RES / "Colors"
TOKENS_SWIFT = ROOT / "ios" / "Demleme" / "Design" / "Tokens.swift"

INFO = {"info": {"author": "xcode", "version": 1}}
HEX_RE = re.compile(r"^#([0-9a-fA-F]{6})$")
RGBA_RE = re.compile(
    r"^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d*\.?\d+)\s*\)$"
)


def parse_color(value):
    """Return (r, g, b, a) as floats in 0...1."""
    m = HEX_RE.match(value)
    if m:
        h = m.group(1)
        return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)) + (1.0,)
    m = RGBA_RE.match(value)
    if m:
        r, g, b = (int(m.group(i)) / 255 for i in (1, 2, 3))
        return (r, g, b, float(m.group(4)))
    raise ValueError(f"unsupported color value: {value!r}")


def entry(value, appearances):
    r, g, b, a = parse_color(value)
    e = {
        "idiom": "universal",
        "color": {
            "color-space": "srgb",
            "components": {
                "red": f"{r:.3f}",
                "green": f"{g:.3f}",
                "blue": f"{b:.3f}",
                "alpha": f"{a:.3f}",
            },
        },
    }
    if appearances:
        e["appearances"] = appearances
    return e


def colorset(token):
    v = token["value"]
    colors = [entry(v["light"], None)]
    dark = [{"appearance": "luminosity", "value": "dark"}]
    high = [{"appearance": "contrast", "value": "high"}]
    colors.append(entry(v["dark"], dark))
    if "contrast" in v:
        colors.append(entry(v["contrast"], high))
        colors.append(entry(v.get("contrast-dark", v["dark"]), dark + high))
    return {"colors": colors, **INFO}


def swift_id(name):
    parts = name.split("-")
    ident = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if not re.match(r"^[a-z][A-Za-z0-9]*$", ident):
        raise ValueError(f"cannot make a Swift identifier from {name!r}")
    return ident


def dumps(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def tokens_swift(names):
    lines = [
        "// Generated by ios/scripts/gen_colors.py from tasarim-sistemi/tokens.json.",
        "// Do not edit by hand.",
        "",
        "import SwiftUI",
        "",
        "/// Named colors from the asset catalog (design tokens).",
        "enum DemlemeColor {",
    ]
    for n in names:
        lines.append(f'    static let {swift_id(n)} = Color("{n}")')
    lines += ["", "    /// Asset catalog names of every token color.", "    static let allNames: [String] = ["]
    for n in names:
        lines.append(f'        "{n}",')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def build():
    """Return {Path: text} for every generated file."""
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    tokens = data["color"]["tokens"]
    files = {
        RES / "Contents.json": dumps(INFO),
        COLORS / "Contents.json": dumps(INFO),
    }
    names = []
    for t in tokens:
        names.append(t["name"])
        files[COLORS / f"{t['name']}.colorset" / "Contents.json"] = dumps(colorset(t))
    files[TOKENS_SWIFT] = tokens_swift(names)
    return files, names


def stale_colorsets(names):
    if not COLORS.exists():
        return []
    return sorted(
        p for p in COLORS.glob("*.colorset") if p.name[: -len(".colorset")] not in names
    )


def main(argv):
    check = "--check" in argv
    files, names = build()
    extras = stale_colorsets(names)
    problems = []
    for path, text in files.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            problems.append(f"stale or missing: {path.relative_to(ROOT)}")
    for p in extras:
        problems.append(f"unexpected: {p.relative_to(ROOT)}")
    if check:
        if problems:
            print("\n".join(problems), file=sys.stderr)
            print("Run: python3 -I ios/scripts/gen_colors.py", file=sys.stderr)
            return 1
        print(f"OK: {len(names)} colors up to date")
        return 0
    for p in extras:
        shutil.rmtree(p)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"Generated {len(names)} colorsets and Tokens.swift")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
