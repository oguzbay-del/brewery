// Generates src/styles/tokens.css from ../tasarim-sistemi/tokens.json.
// Usage: node scripts/gen-tokens.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '../tasarim-sistemi/tokens.json');
const target = resolve(root, 'src/styles/tokens.css');

const tokens = JSON.parse(readFileSync(source, 'utf8'));

const decls = (items, indent) => items.map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');
const colorsFor = (theme) =>
  tokens.color.tokens
    .filter((t) => t.value[theme] !== undefined)
    .map((t) => [t.name, t.value[theme]]);

const themeIds = tokens.color.themes.map((t) => t.id);
for (const required of ['light', 'dark', 'contrast']) {
  if (!themeIds.includes(required)) throw new Error(`tokens.json: theme "${required}" missing`);
}

const plain = (group) => tokens[group].tokens.map((t) => [t.name, t.value]);
const fonts = Object.entries(tokens.type.families).map(([k, v]) => [`font-${k}`, v]);
const styles = tokens.type.groups
  .flatMap((g) => g.styles)
  .flatMap((s) => [
    [`${s.name}-size`, s.fontSize],
    [`${s.name}-line`, s.lineHeight],
    [`${s.name}-weight`, String(s.fontWeight)],
  ]);

const out = [
  '/* GENERATED by scripts/gen-tokens.mjs from tasarim-sistemi/tokens.json. Do not edit. */',
  '',
  ':root {',
  '  color-scheme: light;',
  decls(colorsFor('light'), '  '),
  decls([...fonts, ...styles, ...plain('spacing'), ...plain('radius'), ...plain('shadow')], '  '),
  '}',
  '',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]):not([data-theme="contrast"]) {',
  '    color-scheme: dark;',
  decls(colorsFor('dark'), '    '),
  '  }',
  '}',
  '',
  ':root[data-theme="dark"] {',
  '  color-scheme: dark;',
  decls(colorsFor('dark'), '  '),
  '}',
  '',
  '/* Contrast overrides only a few tokens on top of the light theme. */',
  '@media (prefers-contrast: more) and (prefers-color-scheme: light) {',
  '  :root:not([data-theme]) {',
  decls(colorsFor('contrast'), '    '),
  '  }',
  '}',
  '',
  ':root[data-theme="contrast"] {',
  decls(colorsFor('contrast'), '  '),
  '}',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('src/styles/tokens.css is out of date. Run: npm run gen:tokens');
    process.exit(1);
  }
  console.log('tokens.css is up to date');
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
